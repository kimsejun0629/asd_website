def expr(W,frameW,lo,hi,t0,t1):
  ks=[k for k in K if t0<=k[0]<t1]
  if not ks: return str(int(lo))
  px=lambda c:max(lo,min(hi,c*frameW-W/2))
  parts=[];prev=None
